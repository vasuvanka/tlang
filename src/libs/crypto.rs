    code.push_str("        if (key_len == 16) cipher = EVP_aes_128_cbc();\n");
    code.push_str("        else if (key_len == 24) cipher = EVP_aes_192_cbc();\n");
    code.push_str("        else if (key_len == 32) cipher = EVP_aes_256_cbc();\n");
    code.push_str("        else { EVP_CIPHER_CTX_free(ctx); return result; }\n");
    code.push_str("    } else if (strcmp(mode, \"ecb\") == 0 || strcmp(mode, \"ECB\") == 0) {\n");
    code.push_str("        if (key_len == 16) cipher = EVP_aes_128_ecb();\n");
    code.push_str("        else if (key_len == 24) cipher = EVP_aes_192_ecb();\n");
    code.push_str("        else if (key_len == 32) cipher = EVP_aes_256_ecb();\n");
    code.push_str("        else { EVP_CIPHER_CTX_free(ctx); return result; }\n");
