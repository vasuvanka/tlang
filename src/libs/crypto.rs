    code.push_str("    if (len % 2 != 0 || len / 2 > max_len) return 0;\n");
    code.push_str("    for (int i = 0; i < len / 2; i++) {\n");
    code.push_str("        int val;\n");
    code.push_str("        sscanf(hex + i * 2, \"%2x\", &val);\n");
    code.push_str("        bytes[i] = (unsigned char)val;\n");
    code.push_str("    }\n");
