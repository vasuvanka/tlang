    code.push_str("    }\n");
    code.push_str("    strcpy(result, base64_encode_simple(encrypted, len));\n");
    code.push_str("    free(encrypted);\n");
    code.push_str("#endif\n");
    code.push_str("    \n");
    code.push_str("    return result;\n");
    code.push_str("}\n\n");
    
    // AES Decryption
    code.push_str("// crypto.AESDecrypt - AES decryption (takes base64 encoded input)\n");
    code.push_str("char* crypto_AESDecrypt(const char* encrypted, const char* key, const char* mode) {\n");
    code.push_str("    static char result[4096];\n");
    code.push_str("    result[0] = '\\0';\n");
    code.push_str("    \n");
    code.push_str("#ifdef USE_OPENSSL\n");
