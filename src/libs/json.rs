    code.push_str("    if (!p) return;\n");
    code.push_str("    for (int i = 0; i < count && p->pos < p->len; i++) {\n");
    code.push_str("        if (p->json[p->pos] == '\\n') {\n");
    code.push_str("            p->line++;\n");
    code.push_str("            p->column = 1;\n");
    code.push_str("        } else {\n");
    code.push_str("            p->column++;\n");
    code.push_str("        }\n");
    code.push_str("        p->pos++;\n");
    code.push_str("    }\n");
    code.push_str("}\n\n");
    
