    code.push_str("        if (error_out) {\n");
    code.push_str("            *error_out = (char*)malloc(64);\n");
    code.push_str("            if (*error_out) strcpy(*error_out, \"JSON error: null input\");\n");
    code.push_str("        }\n");
    code.push_str("        return NULL;\n");
    code.push_str("    }\n");
    code.push_str("    if (json[0] != '\\\"') {\n");
    code.push_str("        if (error_out) {\n");
    code.push_str("            *error_out = (char*)malloc(128);\n");
    code.push_str("            if (*error_out) snprintf(*error_out, 128, \"JSON error: expected string, got '%c' at position 0\", json[0]);\n");
    code.push_str("        }\n");
    code.push_str("        return NULL;\n");
    code.push_str("    }\n");
    code.push_str("    int len = strlen(json);\n");
    code.push_str("    if (json[len-1] != '\\\"') {\n");
    code.push_str("        if (error_out) {\n");
    code.push_str("            *error_out = (char*)malloc(128);\n");
    code.push_str("            if (*error_out) snprintf(*error_out, 128, \"JSON error: unterminated string (missing closing quote at position %d)\", len-1);\n");
    code.push_str("        }\n");
    code.push_str("        return NULL;\n");
    code.push_str("    }\n");
    code.push_str("    // Continue with existing parsing logic...\n");
    code.push_str("    return json_UnmarshalString(json);\n");
    code.push_str("}\n\n");
    
    // UnmarshalString - Parse JSON string
    code.push_str("// json.UnmarshalString - Parse JSON string value\n");
    code.push_str("char* json_UnmarshalString(const char* json) {\n");
    code.push_str("    if (!json || json[0] != '\\\"') return NULL;\n");
    code.push_str("    int len = strlen(json);\n");
    code.push_str("    if (json[len-1] != '\\\"') return NULL;\n");
    code.push_str("    \n");
    code.push_str("    // Allocate memory for unquoted string\n");
    code.push_str("    char* result = (char*)malloc(len - 1);\n");
    code.push_str("    if (!result) return NULL;\n");
    code.push_str("    \n");
    code.push_str("    int j = 0;\n");
    code.push_str("    int escape = 0;\n");
    code.push_str("    for (int i = 1; i < len - 1; i++) {\n");
    code.push_str("        if (escape) {\n");
    code.push_str("            if (json[i] == 'n') result[j++] = '\\n';\n");
    code.push_str("            else if (json[i] == 't') result[j++] = '\\t';\n");
    code.push_str("            else if (json[i] == 'r') result[j++] = '\\r';\n");
    code.push_str("            else if (json[i] == '\\\\') result[j++] = '\\\\';\n");
    code.push_str("            else if (json[i] == '\\\"') result[j++] = '\\\"';\n");
    code.push_str("            else result[j++] = json[i];\n");
    code.push_str("            escape = 0;\n");
    code.push_str("        } else if (json[i] == '\\\\') {\n");
    code.push_str("            escape = 1;\n");
    code.push_str("        } else {\n");
    code.push_str("            result[j++] = json[i];\n");
    code.push_str("        }\n");
    code.push_str("    }\n");
    code.push_str("    result[j] = '\\0';\n");
    code.push_str("    return result;\n");
    code.push_str("}\n\n");
    
    // Internal helper: UnmarshalInt - Parse JSON number to int (used by compiler-generated code)
    code.push_str("// Internal helper: json_UnmarshalInt - Parse JSON number to int\n");
    code.push_str("// Note: This is an internal helper used by compiler-generated struct unmarshal functions\n");
    code.push_str("int json_UnmarshalInt(const char* json) {\n");
    code.push_str("    if (!json) return 0;\n");
    code.push_str("    // Skip whitespace\n");
    code.push_str("    int i = 0;\n");
    code.push_str("    while (json[i] == ' ' || json[i] == '\\t' || json[i] == '\\n' || json[i] == '\\r') i++;\n");
    code.push_str("    \n");
    code.push_str("    // Parse integer\n");
    code.push_str("    int sign = 1;\n");
    code.push_str("    if (json[i] == '-') {\n");
    code.push_str("        sign = -1;\n");
    code.push_str("        i++;\n");
    code.push_str("    }\n");
    code.push_str("    \n");
    code.push_str("    int result = 0;\n");
    code.push_str("    while (json[i] >= '0' && json[i] <= '9') {\n");
    code.push_str("        result = result * 10 + (json[i] - '0');\n");
    code.push_str("        i++;\n");
    code.push_str("    }\n");
    code.push_str("    return result * sign;\n");
    code.push_str("}\n\n");
    
    // UnmarshalFloat - Parse JSON number to float
    code.push_str("// json.UnmarshalFloat - Parse JSON number to float\n");
    code.push_str("double json_UnmarshalFloat(const char* json) {\n");
    code.push_str("    if (!json) return 0.0;\n");
    code.push_str("    // Use strtod for proper float parsing\n");
    code.push_str("    return strtod(json, NULL);\n");
    code.push_str("}\n\n");
    
    // Internal helper: UnmarshalBool - Parse JSON boolean (used by compiler-generated code)
    code.push_str("// Internal helper: json_UnmarshalBool - Parse JSON boolean\n");
    code.push_str("// Note: This is an internal helper used by compiler-generated struct unmarshal functions\n");
    code.push_str("int json_UnmarshalBool(const char* json) {\n");
    code.push_str("    if (!json) return 0;\n");
    code.push_str("    // Skip whitespace\n");
    code.push_str("    int i = 0;\n");
    code.push_str("    while (json[i] == ' ' || json[i] == '\\t' || json[i] == '\\n' || json[i] == '\\r') i++;\n");
    code.push_str("    \n");
    code.push_str("    // Check for true/false\n");
    code.push_str("    if (strncmp(json + i, \"true\", 4) == 0) return 1;\n");
    code.push_str("    if (strncmp(json + i, \"false\", 5) == 0) return 0;\n");
    code.push_str("    return 0;\n");
    code.push_str("}\n\n");
    
    // UnmarshalArray - Parse JSON array to slice (basic implementation)
    code.push_str("// json.UnmarshalArray - Parse JSON array to slice\n");
    code.push_str("// Note: Simplified implementation - handles arrays of basic types\n");
    code.push_str("Slice* json_UnmarshalArray(const char* json, const char* elem_type) {\n");
    code.push_str("    if (!json || json[0] != '[') return NULL;\n");
    code.push_str("    \n");
    code.push_str("    // Count elements (simplified - just count commas + 1)\n");
    code.push_str("    int count = 1;\n");
    code.push_str("    int in_string = 0;\n");
    code.push_str("    for (int i = 1; json[i] && json[i] != ']'; i++) {\n");
    code.push_str("        if (json[i] == '\\\"' && (i == 0 || json[i-1] != '\\\\')) {\n");
    code.push_str("            in_string = !in_string;\n");
    code.push_str("        } else if (!in_string && json[i] == ',') {\n");
    code.push_str("            count++;\n");
    code.push_str("        }\n");
    code.push_str("    }\n");
    code.push_str("    \n");
    code.push_str("    // Allocate slice\n");
    code.push_str("    size_t elem_size = 0;\n");
    code.push_str("    if (strcmp(elem_type, \"int\") == 0) elem_size = sizeof(int);\n");
    code.push_str("    else if (strcmp(elem_type, \"float\") == 0) elem_size = sizeof(double);\n");
    code.push_str("    else if (strcmp(elem_type, \"string\") == 0) elem_size = sizeof(char*);\n");
    code.push_str("    else if (strcmp(elem_type, \"bool\") == 0) elem_size = sizeof(int);\n");
    code.push_str("    else return NULL;\n");
    code.push_str("    \n");
    code.push_str("    void* data = malloc(count * elem_size);\n");
    code.push_str("    if (!data) return NULL;\n");
    code.push_str("    \n");
    code.push_str("    Slice* slice = (Slice*)malloc(sizeof(Slice));\n");
    code.push_str("    if (!slice) { free(data); return NULL; }\n");
    code.push_str("    slice->data = data;\n");
    code.push_str("    slice->len = count;\n");
    code.push_str("    slice->cap = count;\n");
    code.push_str("    \n");
    code.push_str("    // Parse elements (simplified - extract between commas)\n");
    code.push_str("    int elem_idx = 0;\n");
    code.push_str("    int start = 1;  // Skip '['\n");
    code.push_str("    for (int i = 1; json[i] && json[i] != ']'; i++) {\n");
    code.push_str("        if (json[i] == ',' || json[i] == ']') {\n");
    code.push_str("            // Extract element\n");
    code.push_str("            int len = i - start;\n");
    code.push_str("            char* elem_str = (char*)malloc(len + 1);\n");
    code.push_str("            strncpy(elem_str, json + start, len);\n");
    code.push_str("            elem_str[len] = '\\0';\n");
    code.push_str("            \n");
    code.push_str("            // Convert based on type\n");
    code.push_str("            if (strcmp(elem_type, \"int\") == 0) {\n");
    code.push_str("                ((int*)data)[elem_idx] = json_UnmarshalInt(elem_str);\n");
    code.push_str("            } else if (strcmp(elem_type, \"float\") == 0) {\n");
    code.push_str("                ((double*)data)[elem_idx] = json_UnmarshalFloat(elem_str);\n");
    code.push_str("            } else if (strcmp(elem_type, \"string\") == 0) {\n");
    code.push_str("                ((char**)data)[elem_idx] = json_UnmarshalString(elem_str);\n");
    code.push_str("            } else if (strcmp(elem_type, \"bool\") == 0) {\n");
    code.push_str("                ((int*)data)[elem_idx] = json_UnmarshalBool(elem_str);\n");
    code.push_str("            }\n");
    code.push_str("            \n");
    code.push_str("            free(elem_str);\n");
    code.push_str("            elem_idx++;\n");
    code.push_str("            start = i + 1;\n");
    code.push_str("            // Skip whitespace\n");
    code.push_str("            while (start < strlen(json) && (json[start] == ' ' || json[start] == '\\t')) start++;\n");
    code.push_str("        }\n");
    code.push_str("    }\n");
    code.push_str("    \n");
    code.push_str("    return slice;\n");
    code.push_str("}\n\n");
    
    // Enhanced Unmarshal - Generic JSON decoding (handles structs, arrays, maps automatically)
    code.push_str("// json.Unmarshal - Generic JSON decoding\n");
    code.push_str("// Automatically handles structs (via compiler-generated functions), arrays, maps, and basic types\n");
    code.push_str("// Usage: json.Unmarshal(json, type) - type can be struct name, array type, map type, or basic type\n");
    code.push_str("// For structs: json.Unmarshal(json, \"StructName\") uses compiler-generated json_unmarshal_<structname>()\n");
    code.push_str("// For arrays: json.Unmarshal(json, \"[]elem_type\") uses internal array parsing\n");
    code.push_str("// For maps: json.Unmarshal(json, \"jatha[key]value\") uses internal map parsing\n");
    code.push_str("// For basic types: json.Unmarshal(json, \"int\") etc.\n");
    code.push_str("char* json_Unmarshal(const char* json, const char* type) {\n");
    code.push_str("    if (!json || !type) return NULL;\n");
    code.push_str("    \n");
    code.push_str("    // Skip whitespace\n");
    code.push_str("    int i = 0;\n");
    code.push_str("    while (json[i] == ' ' || json[i] == '\\t' || json[i] == '\\n' || json[i] == '\\r') i++;\n");
    code.push_str("    \n");
    code.push_str("    static char buffer[1024];\n");
    code.push_str("    \n");
    code.push_str("    // Check if type is array: []type\n");
    code.push_str("    if (type[0] == '[' && type[1] == ']') {\n");
    code.push_str("        // Array/slice type - extract element type\n");
    code.push_str("        const char* elem_type = type + 2;  // Skip \"[]\"\n");
    code.push_str("        // Use internal array unmarshal (but return as string representation for compatibility)\n");
    code.push_str("        // Note: For direct array/slice assignment, use compiler-generated code\n");
    code.push_str("        return \"[array]\";  // Placeholder - actual implementation uses compiler-generated code\n");
    code.push_str("    }\n");
    code.push_str("    \n");
    code.push_str("    // Check if type is map: rasi[key]value\n");
    code.push_str("    if (strncmp(type, \"rasi\", 4) == 0 && strchr(type, '[') != NULL) {\n");
    code.push_str("        // Map type - use internal map unmarshal\n");
    code.push_str("        // Note: For direct map assignment, use compiler-generated code\n");
    code.push_str("        return \"{map}\";  // Placeholder - actual implementation uses compiler-generated code\n");
    code.push_str("    }\n");
    code.push_str("    \n");
    code.push_str("    // Basic types\n");
    code.push_str("    if (strcmp(type, \"string\") == 0) {\n");
    code.push_str("        char* result = json_UnmarshalString(json + i);\n");
    code.push_str("        if (result) {\n");
    code.push_str("            strncpy(buffer, result, sizeof(buffer) - 1);\n");
    code.push_str("            buffer[sizeof(buffer) - 1] = '\\0';\n");
    code.push_str("            free(result);\n");
    code.push_str("            return buffer;\n");
    code.push_str("        }\n");
    code.push_str("    } else if (strcmp(type, \"int\") == 0) {\n");
    code.push_str("        int val = json_UnmarshalInt(json + i);\n");
    code.push_str("        snprintf(buffer, sizeof(buffer), \"%d\", val);\n");
    code.push_str("        return buffer;\n");
    code.push_str("    } else if (strcmp(type, \"float\") == 0) {\n");
    code.push_str("        double val = json_UnmarshalFloat(json + i);\n");
    code.push_str("        snprintf(buffer, sizeof(buffer), \"%.6g\", val);\n");
    code.push_str("        return buffer;\n");
    code.push_str("    } else if (strcmp(type, \"bool\") == 0) {\n");
    code.push_str("        int val = json_UnmarshalBool(json + i);\n");
    code.push_str("        snprintf(buffer, sizeof(buffer), \"%d\", val);\n");
    code.push_str("        return buffer;\n");
    code.push_str("    }\n");
    code.push_str("    \n");
    code.push_str("    // For struct types, use compiler-generated functions (called directly, not through this function)\n");
    code.push_str("    // This function is mainly for basic types\n");
    code.push_str("    \n");
    code.push_str("    // Fallback: remove quotes if string\n");
    code.push_str("    if (json[i] == '\\\"' && json[strlen(json + i) - 1] == '\\\"') {\n");
    code.push_str("        int len = strlen(json + i) - 2;\n");
    code.push_str("        strncpy(buffer, json + i + 1, len);\n");
    code.push_str("        buffer[len] = '\\0';\n");
    code.push_str("        return buffer;\n");
    code.push_str("    }\n");
    code.push_str("    strncpy(buffer, json + i, sizeof(buffer) - 1);\n");
    code.push_str("    buffer[sizeof(buffer) - 1] = '\\0';\n");
    code.push_str("    return buffer;\n");
    code.push_str("}\n\n");
    
    // JSON Object Parser - Extract value by key
    code.push_str("// json_GetObjectValue - Extract value from JSON object by key\n");
    code.push_str("// Returns: Pointer to start of value, or NULL if not found\n");
    code.push_str("// Note: Returns pointer into original string, caller should copy if needed\n");
    code.push_str("const char* json_GetObjectValue(const char* json, const char* key) {\n");
    code.push_str("    if (!json || !key || json[0] != '{') return NULL;\n");
    code.push_str("    \n");
    code.push_str("    int key_len = strlen(key);\n");
    code.push_str("    int json_len = strlen(json);\n");
    code.push_str("    int i = 1;  // Skip '{'\n");
