    code.push_str("void json_skip_whitespace(JSONParser* p) {\n");
    code.push_str("    if (!p) return;\n");
    code.push_str("    while (p->pos < p->len) {\n");
    code.push_str("        char c = p->json[p->pos];\n");
    code.push_str("        if (c == ' ' || c == '\\t' || c == '\\n' || c == '\\r') {\n");
    code.push_str("            json_parser_advance(p, 1);\n");
    code.push_str("        } else {\n");
    code.push_str("            break;\n");
    code.push_str("        }\n");
    code.push_str("    }\n");
    code.push_str("}\n\n");
    
